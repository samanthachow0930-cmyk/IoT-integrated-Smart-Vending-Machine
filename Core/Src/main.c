void USART_SendString(UART_HandleTypeDef *huart, char *str) {
	while (*str) {
		HAL_UART_Transmit(huart, (uint8_t*) str, 1, HAL_MAX_DELAY);
		str++;
	}
}

void Send_Stock_To_ESP32(void) {
	// Format: "STOCK,<coffee_stock>,<biscuits_stock>\n"
	// Coffee is item 1, Biscuits is item 2
	snprintf(tx_buffer, sizeof(tx_buffer), "STOCK,%ld,%ld\n", items[0].stock, // Coffee stock
			items[1].stock);  // Biscuits stock

	USART_SendString(&huart4, tx_buffer);

	// Also print to UART4 for debugging
	char debug_msg[64];
	sprintf(debug_msg, "STOCK SENT: Coffee=%ld, Biscuits=%ld\n", items[0].stock,
			items[1].stock);
	HAL_UART_Transmit(&huart4, (uint8_t*) debug_msg, strlen(debug_msg),
	HAL_MAX_DELAY);
}

