/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_FSMC_Init();
  MX_DMA_Init();
  MX_UART4_Init();
  MX_SPI2_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  /* USER CODE BEGIN 2 */

// Initialize the LCD
	LCD_INIT();

	// Initialize RC522
	MFRC522_Init(&rfID);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
	while (1) {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
		switch (current_state) {
		case STATE_INIT: {
			total_paid = 0;
			selected_item = 0;
			selected_price = 0;
			Send_Stock_To_ESP32();
			current_state = STATE_SELECTION;
			LCD_Clear(0, 0, 240, 320, 0XFFFF);
			break;
		}
		case STATE_SELECTION: {
			LCD_DrawString(0, 0, "Please pick item");
			LCD_DrawString(0, 30, "Press 1 or 2");
			char item = get_keypad_key();

			int index = item - '1';
			if (index >= 0 && index < 2) {
				if (items[index].stock > 0) {
					items[index].stock--;
					LCD_DrawString(0, 60, "Stock OK - Proceed");
					selected_item = items[index].item_id;
					selected_price = items[index].price;
					LCD_Clear(0, 0, 240, 320, 0XFFFF);
					current_state = STATE_PAYMENT;
				} else {
					LCD_DrawString(0, 60, "Out of stock!");
				}
			} else if (item != 0) {
				LCD_DrawString(0, 60, "Press a valid choice");
			}
			break;
		}

		case STATE_PAYMENT: {
			char item_msg[30];
			sprintf(item_msg, "Item %d selected", selected_item);
			LCD_DrawString(0, 0, item_msg);

			char price_msg[30];
			sprintf(price_msg, "Price: %lu", selected_price);
			LCD_DrawString(0, 30, price_msg);

			LCD_DrawString(0, 60, "Payment selection:");
			LCD_DrawString(0, 90, "Press A for card payment...");
			LCD_DrawString(0, 120, "Press B for coin payment...");

			char payment_mode = get_keypad_key();
			if (payment_mode == 'A') {
				octopus_selected = 1;
				current_state = STATE_WAITING_CARD;
				LCD_Clear(0, 0, 240, 320, 0XFFFF);
			} else if (payment_mode == 'B') {
				LCD_Clear(0, 0, 240, 320, 0XFFFF);
				coin_selected = 1;
				current_state = STATE_WAITING_COINS;
				HAL_NVIC_EnableIRQ(EXTI4_IRQn);
				HAL_NVIC_EnableIRQ(EXTI9_5_IRQn);
			} else if (payment_mode != 0) {
				LCD_DrawString(0, 150, "Please press either A or B");
			}
			break;
		}

		case STATE_WAITING_CARD: {
			LCD_DrawString(0, 0, "Please tap your card");
			if (waitcardDetect(&rfID) == STATUS_OK) {
				if (MFRC522_ReadUid(&rfID, uid) == STATUS_OK) {
					LCD_DrawString(0, 30, "Card payment done");
					HAL_Delay(500);
					LCD_Clear(0, 0, 240, 320, 0XFFFF);
					current_state = STATE_PAYMENT_DONE;
				}
			}
			break;
		}

		case STATE_WAITING_COINS: {
			char item_msg[30];
			sprintf(item_msg, "Item %d selected", selected_item);
			LCD_DrawString(0, 0, item_msg);

			char price_msg[30];
			sprintf(price_msg, "Price: %lu", selected_price);
			LCD_DrawString(0, 30, price_msg);
			char count_msg[30];
			sprintf(count_msg, "Coin inserted: $ %lu", total_paid);
			LCD_DrawString(0, 60, count_msg);
			if (total_paid >= selected_price) {
				LCD_Clear(0, 0, 240, 320, 0xFFFF);
				current_state = STATE_PAYMENT_DONE;
			}
			break;
		}

		case STATE_PAYMENT_DONE: {
			HAL_NVIC_DisableIRQ(EXTI4_IRQn);
			HAL_NVIC_DisableIRQ(EXTI9_5_IRQn);
			LCD_DrawString(0, 0, "Thank you!");
			LCD_DrawString(0, 30, "Please wait for your item.");
			current_state = STATE_DISPENSING_PRODUCT;
			break;
		}

		case STATE_DISPENSING_PRODUCT: {
			if (selected_item == 1) {
				TIM1->CCER |= (TIM_CCER_CC2E);
				HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
				TIM1->CCR2 = 1200;
				HAL_Delay(1700);
				TIM1->CCER &= ~(TIM_CCER_CC2E);
			} else if (selected_item == 2){
				HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_4);
				TIM2->CCR4 = 1800;
				HAL_Delay(1000);
				HAL_TIM_PWM_Stop(&htim2, TIM_CHANNEL_4);
			}
			current_state = STATE_INIT;
			break;
		}
		default:
			break;
		}
	}
  /* USER CODE END 3 */
}

